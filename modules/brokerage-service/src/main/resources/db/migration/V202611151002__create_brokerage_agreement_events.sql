-- The history of a brokerage agreement (brokerage-agreement E05-S2 spec 5.3, S2-D8). Insert-only. BR-17: a row holds the
-- event, the actor, the time and the version only, no reason and no value; event_type is a fixed enum name with no
-- CHECK, as inventory_intake_events.action, so later slices add events without a migration. actor_user_id names a user
-- of auth-service and is NULL for an event with no staff actor.
SET LOCAL lock_timeout = '5s';

CREATE TABLE brokerage_agreement_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    agreement_id VARCHAR(26) NOT NULL,
    version_no INTEGER,
    event_type VARCHAR(40) NOT NULL,
    actor_user_id VARCHAR(26),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT brokerage_agreement_events_pkey PRIMARY KEY (id),
    CONSTRAINT fk_brokerage_agreement_events_agreement FOREIGN KEY (agreement_id) REFERENCES brokerage_agreements (id)
);

CREATE INDEX idx_brokerage_agreement_events_agreement_id ON brokerage_agreement_events (agreement_id);
