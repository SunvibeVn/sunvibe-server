-- Who opened which brokerage agreement and when (brokerage-agreement E05-S2 spec 5.3, S2-D9; BR-17: opening the detail
-- of an agreement is logged). Insert-only, with no foreign key: a log outlives what it names, and user_id and
-- agreement_id are plain ids. It holds no value of the agreement; action is a fixed enum name. Retention has no policy
-- yet (brokerage-agreement Q-2, SV-117).
SET LOCAL lock_timeout = '5s';

CREATE TABLE brokerage_agreement_access_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id VARCHAR(26) NOT NULL,
    agreement_id VARCHAR(26) NOT NULL,
    action VARCHAR(40) NOT NULL,
    accessed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT brokerage_agreement_access_logs_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_brokerage_agreement_access_logs_agreement_accessed
    ON brokerage_agreement_access_logs (agreement_id, accessed_at);
