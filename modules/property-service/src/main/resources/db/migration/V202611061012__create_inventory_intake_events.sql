-- The trail of assignee commands (property-create intake spec 4.1 I-4, 5.2 file 11, BR-12): the actor set of D5-7 and D5-15.
-- Insert-only. action is a fixed enum name: no free text, code, phrase or address. actor_user_id names a user of
-- auth-service, and is NULL for a command with no staff actor.
SET LOCAL lock_timeout = '5s';

CREATE TABLE inventory_intake_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    intake_id VARCHAR(26) NOT NULL,
    actor_user_id VARCHAR(26),
    action VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT inventory_intake_events_pkey PRIMARY KEY (id),
    CONSTRAINT fk_inventory_intake_events_intake_id FOREIGN KEY (intake_id) REFERENCES inventory_intakes (id)
);

CREATE INDEX idx_inventory_intake_events_intake_id ON inventory_intake_events (intake_id);
