-- Who read what (property-create intake spec 4.12, 5.2 file 12, BR-14): search, case read, owner-check context, preview, block
-- read. Insert-only, with no foreign key: a log outlives what it names, and intake_id and case_id are plain ids. It holds no
-- phone, email, code, phrase, address or search text. Retention has no policy yet (spec 2.4 item 1, T-4).
CREATE TABLE inventory_access_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id VARCHAR(26) NOT NULL,
    lead_id VARCHAR(26) NOT NULL,
    intake_id VARCHAR(26),
    case_id VARCHAR(26),
    action VARCHAR(40) NOT NULL,
    accessed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT inventory_access_logs_pkey PRIMARY KEY (id)
);
